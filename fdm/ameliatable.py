"""Amelia's take-off table: where this model's stick, pedals and attitude have to be for a take-off, by wind, weight and
air density, from trims of the model itself. It is written into Alouette-3/Systems/amelia.xml, between its markers.
(Aerospatiale's type specification has no take-off wind table, so none of this is the manufacturer's.)

For every weight, density and wind: the hover with the wheels 1 ft up (stick, pedals, attitude, collective, power),
and, with the collective at 40, 60 and 80 % of that hover's, the pedal at which there is no yaw moment (the helicopter
level, the stick at the same part of its hover place): on the wheels the nose swings with the wind well before the
helicopter is light, so the pedal is needed all the way up the lever. The wind is flown as airspeed, the helicopter
moving towards where the wind comes from. The trims are made at one centre of gravity; the fore-and-aft and side
shifts of stick and attitude with it, which depend on the weight, are measured too.

  python3 ameliatable.py            trim (4 processes, some minutes: use the queue) and write the file
  python3 ameliatable.py --pedals   the pedals on the wheels again, on the hover trims in data/al3_takeoff_trims.json
  python3 ameliatable.py --write    write the file again from data/al3_takeoff_trims.json

Needs fdm/root (python3 genal3.py root)."""
import json, math, os, sys
from multiprocessing import Pool
import al3data as U
import harness as H
from atmosphere import isa

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data', 'al3_takeoff_trims.json')
XML = os.path.join(HERE, '..', 'Alouette-3', 'Systems', 'amelia.xml')
BEGIN = '<!-- take-off table: begin (generated by fdm/ameliatable.py: edit that, not this) -->'
END = '<!-- take-off table: end -->'

WEIGHTS = (1300.0, 1750.0, 2200.0)      # kg, gross
SIGMAS = (0.70, 0.90, 1.10)             # air density over sea level standard (0.70: about 3000 m on a warm day)
SPEEDS = (0.0, 10.0, 20.0, 30.0)        # wind, kt
FROMS = tuple(range(0, 360, 45))        # where it comes from, deg from the nose, clockwise
FRACTIONS = (0.4, 0.6, 0.8)             # of the hover's collective, for the pedal on the wheels
CG_REF = (115.36, 0.0)                  # the centre of gravity of the trims: station and side, in
HOVER_WHEELS_FT, YAW_WHEELS_FT = 1.0, 0.35      # (the second just clear of the ground, so that the gear adds nothing)
CALM_GUESS = [0.6, -0.38, -0.09, 0.2, 0.0, 4.0]
KT_FPS = 1.68781
RHO0 = isa(0.0)[2]


def air(sig):
    """altitude (m) and temperature above standard (C) for a density ratio: the standard atmosphere's altitude, or sea
    level on a cold day for air denser than standard"""
    if sig > 1.0:
        return 0.0, 288.15 / sig - 288.15
    lo, hi = 0.0, 11000.0
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if isa(mid)[2] / RHO0 > sig else (lo, mid)
    return 0.5 * (lo + hi), 0.0


class Sideways:
    """H.residual sets no east speed: this puts one in"""
    def __init__(s, f, ve):
        s.__dict__.update(f=f, ve=ve)

    def __getitem__(s, k):
        return s.f[k]

    def __setitem__(s, k, v):
        s.f[k] = s.ve if k == 'ic/ve-fps' else v

    def __getattr__(s, n):
        return getattr(s.f, n)


class Aircraft:
    """one weight and density, with the centre of gravity at CG_REF plus a shift"""
    def __init__(s, kg, sig, dx=0.0, dy=0.0):
        import genal3
        # the loading variants can only be loaded upwards: below 1750 kg FlightGear's own loading (1441 kg)
        model = 'al3-2200' if kg >= 2199 else ('al3-1750' if kg >= 1749 else 'alouette3')
        s.f = f = H.load(model=model, hold_rpm=True)
        H.set_weight(f, kg)
        alt_m, dT = air(sig)
        f['atmosphere/delta-T'] = dT * 1.8
        s.alt = alt_m / 0.3048
        H.residual(f, CALM_GUESS, 0.0, s.alt, terrain_ft=s.below(HOVER_WHEELS_FT), ned=(0.0, 0.0))
        i = genal3.PM_TANK                      # the whole centre of gravity is moved by moving the fuel's station
        k = f['inertia/weight-lbs'] / f['inertia/pointmass-weight-lbs[%d]' % i]
        for axis, now, want in (('X', f['inertia/cg-x-in'], CG_REF[0] + dx), ('Y', f['inertia/cg-y-in'], CG_REF[1] + dy)):
            name = 'inertia/pointmass-location-%s-inches[%d]' % (axis, i)
            f[name] = f[name] + (want - now) * k
        # (a freshly loaded model's first run has the default controls)
        H.residual(f, CALM_GUESS, 0.0, s.alt, terrain_ft=s.below(HOVER_WHEELS_FT), ned=(0.0, 0.0))
        assert abs(f['inertia/cg-x-in'] - CG_REF[0] - dx) < 0.05 and abs(f['inertia/cg-y-in'] - CG_REF[1] - dy) < 0.05

    def below(s, wheels_ft):
        return s.alt - wheels_ft - H.wheels_above_ground_ft(s.f)

    def wind(s, kt, frm):
        v = kt * KT_FPS
        return Sideways(s.f, v * math.sin(math.radians(frm))), (v * math.cos(math.radians(frm)), 0.0)

    def hover(s, kt, frm, x0):
        f, ned = s.wind(kt, frm)
        x, r, e = H.trim(f, 0.0, s.alt, x0=x0, terrain_ft=s.below(HOVER_WHEELS_FT), ned=ned, extra=H.ENGINE_POWER, iters=24)
        err = float(max(abs(r[:3]).max(), abs(r[3:]).max() * 10))
        return dict(coll=float(x[0]), lon=float(x[1]), lat=float(x[2]), ped=float(x[3]), pitch=float(x[4]), bank=float(x[5]),
                    kw=float(e[0] * e[1] * 1.355818 / 1000), ok=err < 0.1), [float(a) for a in x]

    def yaw_pedal(s, kt, frm, coll, lon, lat, guess):
        """the pedal for no yaw acceleration, where more right pedal turns the nose more to the right: stepped to from the
        guess until the sign changes, then closed in on (false position, Illinois). In a strong wind from the right the
        tail rotor works in its own wake and the curve has a dip part of the way along the pedals: stepping walks
        through it. Returns (pedal, solved); a pedal at its stop with no change of sign is not solved"""
        H.freeze(s.f)
        f, ned = s.wind(kt, frm)

        def rdot(p):
            return H.residual(f, [coll, lon, lat, p, 0.0, 0.0], 0.0, s.alt, terrain_ft=s.below(YAW_WHEELS_FT), ned=ned)[0][5]
        a = max(-1.0, min(1.0, guess))
        ra = rdot(a)
        step = -0.12 if ra > 0 else 0.12
        while True:
            b = max(-1.0, min(1.0, a + step))
            if b == a:
                return float(a), bool(abs(ra) < 0.02)
            rb = rdot(b)
            if (rb > 0) != (ra > 0):
                break
            a, ra = b, rb
        side = 0
        for _ in range(14):
            c = b - rb * (b - a) / (rb - ra)
            rc = rdot(c)
            if abs(rc) < 0.006 or abs(b - a) < 0.004:
                return float(c), True
            if (rc > 0) == (rb > 0):
                b, rb = c, rc
                if side == -1:
                    ra *= 0.5
                side = -1
            else:
                a, ra = c, rc
                if side == 1:
                    rb *= 0.5
                side = 1
        return float(c), bool(abs(rc) < 0.02)


def pedals_on_wheels(a, r):
    """the pedal at each part of the hover's collective, from the hover's pedal downwards, each from the one above"""
    guess = r['ped'] - 0.1
    for fr in sorted(FRACTIONS, reverse=True):
        p, ok = a.yaw_pedal(r['kt'], r['frm'], fr * r['coll'], fr * r['lon'], fr * r['lat'], guess)
        r['ped%d' % round(100 * fr)] = p
        r['ok%d' % round(100 * fr)] = ok
        guess = p - 0.05


def job(task):
    """the winds from some directions at one weight and density, each speed starting from the one below"""
    kg, sig, froms = task
    a = Aircraft(kg, sig)
    calm, xc = a.hover(0.0, 0.0, CALM_GUESS)
    if not calm['ok']:
        calm, xc = a.hover(0.0, 0.0, xc)
    out = []
    for frm in froms:
        x0 = xc
        for kt in SPEEDS:
            if kt == 0.0:
                r, x = dict(calm), xc
            else:
                r, x = a.hover(kt, frm, x0)
                if not r['ok']:
                    r, x = a.hover(kt, frm, x)
            r.update(kg=kg, sigma=sig, kt=kt, frm=frm)
            pedals_on_wheels(a, r)
            out.append(r)
            if r['ok']:
                x0 = x
    return out


def yaw_job(rows):
    """the pedals on the wheels again, for hover trims already made (one weight and density)"""
    a = Aircraft(rows[0]['kg'], rows[0]['sigma'])
    for r in rows:
        pedals_on_wheels(a, r)
    return rows


def recompute_pedals(d, workers=4):
    keys = sorted({(r['kg'], r['sigma'], r['frm'] % 90 == 0) for r in d['points']})
    tasks = [[r for r in d['points'] if (r['kg'], r['sigma'], r['frm'] % 90 == 0) == k] for k in keys]
    points = []
    with Pool(workers) as pool:
        for i, rows in enumerate(pool.imap_unordered(yaw_job, tasks)):
            points += rows
            print('pedals solved for %d of %d blocks' % (i + 1, len(tasks)), flush=True)
    d['points'] = sorted(points, key=lambda r: (r['kg'], r['sigma'], r['kt'], r['frm']))
    return d


def cg_slopes():
    """stick and attitude per inch the centre of gravity moves aft (station) and right, at the lightest and heaviest
    weight, in calm sea level air"""
    out = {}
    for kg in (WEIGHTS[0], WEIGHTS[-1]):
        got = {}
        for name, dx, dy in (('aft', 4.0, 0.0), ('fore', -4.0, 0.0), ('right', 0.0, 2.0), ('left', 0.0, -2.0)):
            got[name] = Aircraft(kg, 1.0, dx, dy).hover(0.0, 0.0, CALM_GUESS)[0]
            assert got[name]['ok'], (kg, name)
        out['%.0f' % kg] = dict(lon_x=(got['aft']['lon'] - got['fore']['lon']) / 8, pitch_x=(got['aft']['pitch'] - got['fore']['pitch']) / 8,
                                lat_y=(got['right']['lat'] - got['left']['lat']) / 4, bank_y=(got['right']['bank'] - got['left']['bank']) / 4)
    return out


def compute(workers=4):
    tasks = [(kg, sig, FROMS[h::2]) for kg in WEIGHTS for sig in SIGMAS for h in range(2)]
    points = []
    with Pool(workers) as pool:
        slopes = pool.apply_async(cg_slopes)
        for i, rows in enumerate(pool.imap_unordered(job, tasks)):
            points += rows
            print('trimmed %d of %d blocks' % (i + 1, len(tasks)), flush=True)
        slopes = slopes.get()
    points.sort(key=lambda r: (r['kg'], r['sigma'], r['kt'], r['frm']))
    return dict(note='generated by fdm/ameliatable.py from trims of the model', cg_ref_in=CG_REF, cg_slopes=slopes, points=points)


# ------------------------------------------------------------------ the file
OUTPUTS = ('coll', 'lon', 'lat', 'ped40', 'ped60', 'ped80', 'ped', 'pitch', 'bank')


def table(points, sig, key, ind, row='wind-kt'):
    """a JSBSim 3-D table: wind speed down, direction across (360 repeating 0), weight by sheet"""
    at = {(r['kg'], r['sigma'], r['kt'], r['frm']): r for r in points}
    t = '\t' * ind
    s = t + '<table>\n'
    for look, var in (('row', row), ('column', 'wind-from-deg'), ('table', 'weight-kg')):
        s += t + '\t<independentVar lookup="%s">systems/amelia/takeoff/%s</independentVar>\n' % (look, var)
    dec = 2 if key in ('pitch', 'bank') else 3
    for kg in WEIGHTS:
        s += t + '\t<tableData breakPoint="%.0f">\n' % kg
        s += t + '\t\t     ' + ''.join('%7d' % a for a in FROMS + (360,)) + '\n'
        for kt in SPEEDS:
            s += t + '\t\t%4.0f ' % kt + ''.join('%7.*f' % (dec, at[(kg, sig, kt, a % 360)][key]) for a in FROMS + (360,)) + '\n'
        s += t + '\t</tableData>\n'
    return s + t + '</table>\n'


def fn(name, body, note=None):
    return '%s\t\t<fcs_function name="%s">\n\t\t<function>\n%s\t\t</function>\n\t\t</fcs_function>\n\n' % (
        '\t\t<!-- %s -->\n' % note if note else '', name, body)


def P(x):
    return '<property>%s</property>' % x


def V(x):
    return '<value>%.7g</value>' % x


def block(d):
    n = 'systems/amelia/takeoff/'
    sl = d['cg_slopes']
    lo, hi = '%.0f' % WEIGHTS[0], '%.0f' % WEIGHTS[-1]

    def per_inch(key):          # linear in the weight, between the lightest and the heaviest
        a, b = sl[lo][key], sl[hi][key]
        return '<sum>%s<product>%s<difference>%s%s</difference></product></sum>' % (
            V(a), V((b - a) / (WEIGHTS[-1] - WEIGHTS[0])), P(n + 'weight-kg'), V(WEIGHTS[0]))

    out = '\t' + BEGIN + '\n'
    out += '''	<!-- What a take-off needs, from trims of this model (stick, pedals, pitch, bank, collective): by the wind (its
	     speed, and where it comes from, deg clockwise from the nose), the weight, and the air density (sea level
	     standard = 1: 0.7, 0.9, 1.1), at a centre of gravity at station %.2f in, in the middle; moved to the centre of
	     gravity she has. pedal40 to pedal80 are the pedal for no yaw with the collective at 40 to 80 %% of the hover's -->
	<channel name="Amelia take-off table" execrate="4">

''' % d['cg_ref_in'][0]
    out += ('\t\t<!-- the wind itself, from ahead and from the right, smoothed over a second: not the airspeed, which in\n'
            '\t\t     flight has the helicopter\'s own movement in it (drifting downwind it would show less wind) -->\n')
    wn, we, psi = P('atmosphere/total-wind-north-fps'), P('atmosphere/total-wind-east-fps'), P('attitude/psi-rad')
    out += fn(n + 'wind-ahead-raw', '\t\t\t<difference><value>0</value><sum><product>%s<cos>%s</cos></product><product>%s<sin>%s</sin></product></sum></difference>\n'
              % (wn, psi, we, psi))
    out += fn(n + 'wind-right-raw', '\t\t\t<difference><product>%s<sin>%s</sin></product><product>%s<cos>%s</cos></product></difference>\n'
              % (wn, psi, we, psi))
    for axis in ('ahead', 'right'):
        out += '\t\t<lag_filter name="%swind-%s-fps">\n\t\t\t<input>%swind-%s-raw</input>\n\t\t\t<c1>1.0</c1>\n\t\t</lag_filter>\n' % (n, axis, n, axis)
    out += '\n'
    ahead, right = P(n + 'wind-ahead-fps'), P(n + 'wind-right-fps')
    out += fn(n + 'wind-kt', '\t\t\t<product>%s<sqrt><sum><pow>%s<value>2</value></pow><pow>%s<value>2</value></pow></sum></sqrt></product>\n'
              % (V(1 / KT_FPS), ahead, right))
    out += fn(n + 'wind-from-deg', '\t\t\t<mod><sum><product><value>57.29578</value><atan2>%s%s</atan2></product><value>360</value></sum><value>360</value></mod>\n'
              % (right, ahead))
    out += fn(n + 'weight-kg', '\t\t\t<quotient>%s<value>2.2046226</value></quotient>\n' % P('inertia/weight-lbs'))
    out += fn(n + 'air-density-ratio', '\t\t\t<quotient>%s%s</quotient>\n' % (P('atmosphere/rho-slugs_ft3'), V(RHO0 / 515.378819)))
    for key in OUTPUTS:
        body = '\t\t\t<interpolate1d>\n\t\t\t\t%s\n' % P(n + 'air-density-ratio')
        for sig in SIGMAS:
            body += '\t\t\t\t%s\n%s' % (V(sig), table(d['points'], sig, key, 4))
        body += '\t\t\t</interpolate1d>\n'
        name = {'ped': 'pedal100', 'ped40': 'pedal40', 'ped60': 'pedal60', 'ped80': 'pedal80'}.get(key, key + '-table')
        out += fn(n + name, body)
    calm = {(r['kg'], r['sigma']): r for r in d['points'] if r['kt'] == 0.0 and r['frm'] == 0}
    body = '\t\t\t<table>\n\t\t\t\t<independentVar lookup="row">%sweight-kg</independentVar>\n\t\t\t\t<independentVar lookup="column">%sair-density-ratio</independentVar>\n\t\t\t\t<tableData>\n' % (n, n)
    body += '\t\t\t\t\t      ' + ''.join('%8.2f' % sig for sig in SIGMAS) + '\n'
    for kg in WEIGHTS:
        body += '\t\t\t\t\t%6.0f' % kg + ''.join('%8.3f' % ((calm[(kg, sg)]['ped'] - calm[(kg, sg)]['ped80']) / (0.2 * calm[(kg, sg)]['coll'])) for sg in SIGMAS) + '\n'
    out += fn(n + 'pedal-per-collective', body + '\t\t\t\t</tableData>\n\t\t\t</table>\n',
              "the torque's share: pedal per unit of collective near the hover, still air")
    out += fn(n + 'no-wind', '\t\t\t<value>0</value>\n', 'the bank table again, read at no wind')
    body = '\t\t\t<interpolate1d>\n\t\t\t\t%s\n' % P(n + 'air-density-ratio')
    for sig in SIGMAS:
        body += '\t\t\t\t%s\n%s' % (V(sig), table(d['points'], sig, 'bank', 4, row='no-wind'))
    out += fn(n + 'bank-still-table', body + '\t\t\t</interpolate1d>\n')
    for key in ('lon', 'lat'):
        body = '\t\t\t<interpolate1d>\n\t\t\t\t%s\n' % P(n + 'air-density-ratio')
        for sig in SIGMAS:
            body += '\t\t\t\t%s\n%s' % (V(sig), table(d['points'], sig, key, 4, row='no-wind'))
        out += fn(n + key + '-still-table', body + '\t\t\t</interpolate1d>\n')
    for key, table_name, slope, axis, ref in (('lon', 'lon-table', 'lon_x', 'x', d['cg_ref_in'][0]), ('lat', 'lat-table', 'lat_y', 'y', d['cg_ref_in'][1]),
                                              ('pitch', 'pitch-table', 'pitch_x', 'x', d['cg_ref_in'][0]), ('bank', 'bank-table', 'bank_y', 'y', d['cg_ref_in'][1]),
                                              ('bank-still', 'bank-still-table', 'bank_y', 'y', d['cg_ref_in'][1]),
                                              ('lon-still', 'lon-still-table', 'lon_x', 'x', d['cg_ref_in'][0]),
                                              ('lat-still', 'lat-still-table', 'lat_y', 'y', d['cg_ref_in'][1])):
        out += fn(n + key, '\t\t\t<sum>\n\t\t\t\t%s\n\t\t\t\t<product>\n\t\t\t\t\t%s\n\t\t\t\t\t<difference>%s%s</difference>\n\t\t\t\t</product>\n\t\t\t</sum>\n'
                  % (P(n + table_name), per_inch(slope), P('inertia/cg-%s-in' % axis), V(ref)),
                  'at the centre of gravity she has' if key == 'lon' else None)
    out += fn(n + 'lever', '\t\t\t<max><value>0</value><min><value>1</value><quotient>%s%s</quotient></min></max>\n'
              % (P('/controls/al3/collective'), P(n + 'coll-table')), "how far up the lever is, towards the hover's")
    for key in ('lon', 'lat'):
        out += fn(n + key + '-on-wheels', '\t\t\t<sum>\n\t\t\t\t<difference>%s%s</difference>\n\t\t\t\t<product>%s%s</product>\n\t\t\t</sum>\n'
                  % (P(n + key), P(n + key + '-still'), P(n + 'lever'), P(n + key + '-still')),
                  "the stick on the wheels: the wind's part whole, even with the lever down (the turning rotor leans away\n"
                  "\t\t     from a wind and can tip the parked helicopter), the still air part with the lever" if key == 'lon' else None)
    body = '\t\t\t<interpolate1d>\n\t\t\t\t%s\n\t\t\t\t<value>0</value><value>0</value>\n' % P(n + 'lever')
    for fr in FRACTIONS + (1.0,):
        body += '\t\t\t\t%s%s\n' % (V(fr), P(n + 'pedal%d' % round(100 * fr)))
    body += '\t\t\t</interpolate1d>\n'
    out += fn(n + 'pedal-on-wheels', body)
    return out.rstrip() + '\n\n\t</channel>\n\t' + END


def write(d):
    t = open(XML).read()
    i, j = t.index(BEGIN), t.index(END) + len(END)
    i = t.rfind('\n', 0, i) + 1
    open(XML, 'w').write(t[:i] + block(d) + t[j:])


def summary(d):
    bad = [r for r in d['points'] if not r['ok']]
    bad_yaw = [r for r in d['points'] if not all(r['ok%d' % round(100 * f)] for f in FRACTIONS)]
    print('%d winds trimmed; hover not solved: %d; pedal on the wheels not solved: %d' % (len(d['points']), len(bad), len(bad_yaw)))
    for r in (bad + bad_yaw)[:12]:
        print('  not solved: %.0f kg sigma %.2f wind %2.0f kt from %3d: pedal %+.2f (%s)' % (r['kg'], r['sigma'], r['kt'], r['frm'], r['ped'],
              ' '.join('%+.2f' % r['ped%d' % round(100 * f)] for f in FRACTIONS)))
    for key in OUTPUTS + ('kw',):
        v = [r[key] for r in d['points']]
        print('  %-6s %+8.2f .. %+8.2f' % (key, min(v), max(v)))
    print('centre of gravity, per inch:', json.dumps(d['cg_slopes']))


if __name__ == '__main__':
    if '--write' in sys.argv:
        data = json.load(open(DATA))
    else:
        data = recompute_pedals(json.load(open(DATA))) if '--pedals' in sys.argv else compute()
        with open(DATA, 'w') as fh:
            json.dump(data, fh, indent=0, sort_keys=True)
    summary(data)
    if not all(r['ok'] and all(r['ok%d' % round(100 * f)] for f in FRACTIONS) for r in data['points']):
        print('NOT writing %s: some trims did not solve' % os.path.basename(XML))
        sys.exit(1)
    write(data)
    print('wrote the take-off table into', os.path.relpath(XML, HERE))
